"""
Management command: sync_staging_to_production

One-time promotion of staging's content into the production database ('default').
Dumps a fixed set of models from staging (connecting to its public Postgres URL)
and loads them into whichever database this command is run against — intended to
be run via `railway run --environment production python manage.py ...` so 'default'
resolves to production.

This is step 4 of the full procedure documented in
docs/promote-staging-to-production.md — it assumes 'default' has already been
flushed and its Wagtail root Page, Locale, and root Collection restored (steps
1-3 of that doc). Running it against a database that still has its own content
will not merge page trees, it will collide/replace.

Usage
-----
    railway run --environment production python manage.py sync_staging_to_production \
        --staging-url "$STAGING_DATABASE_PUBLIC_URL" --dry-run

    railway run --environment production python manage.py sync_staging_to_production \
        --staging-url "$STAGING_DATABASE_PUBLIC_URL"

Optional flags
--------------
--staging-url     Staging's public Postgres URL (default: $STAGING_DATABASE_PUBLIC_URL).
--fixture-path    Where to write the combined dump (default: BASE_DIR/staging_sync_fixture.json,
                   kept on disk afterward as an audit trail — not auto-deleted).
--dry-run         Dump from staging and report per-model counts only; never loads into
                   the target database.
--noinput         Skip the confirmation prompt before loading (scripted/dry-run use only).

Models included
----------------
wagtailcore.page (depth >= 2 only — the root page, depth=1, is excluded so it never
collides with the target's freshly-recreated root), blog.homepage,
blog.projectsindexpage, blog.projectpage, blog.aboutpage, blog.category, the full
pigments app, wagtailimages.image.

Dumped by plain PK (no --natural-foreign/--natural-primary): the target is always
emptied first, so plain PKs load in cleanly for the content itself, and natural
keys would actually break this — wagtailcore.Collection.natural_key() walks
get_ancestors(), which always queries the 'default' alias regardless of which
database the instance came from, so it silently resolves against the wrong
database when staging != default.

ContentType, Collection, and Locale are different: their *rows* already exist
on both databases independently (each created its own via migrations), but
their pks are NOT guaranteed to line up — confirmed in testing, where two
independently migrated databases assigned different pks to the same
(app_label, model) content types because incremental migration history
affects post_migrate's creation order. So wagtailcore.page.content_type,
wagtailcore.page.locale, and wagtailimages.image.collection values from
staging are remapped to the target's pk for the same identity before loading
— see _remap_shared_references(). If a referenced row has no counterpart at
all on the target, the command aborts rather than load a dangling/wrong
reference.

Any other foreign key pointing at a deliberately-excluded model (Page.owner,
Page.locked_by, Page.live_revision, Page.latest_revision -> auth.User /
wagtailcore.Revision; Image.uploaded_by_user -> auth.User) is nulled out in
the dumped fixture instead — see FIELDS_TO_NULL below. All of these are
nullable fields, so the content itself isn't affected: Wagtail copies
published field values onto the Page row itself, so only incidental
metadata/history pointers are reset.

Models excluded, on purpose
----------------------------
contenttypes, sessions            — regenerated by Django itself; staging/target pks
                                     are remapped by identity (see above), not copied.
auth.user, auth.group,
auth.permission                   — editors keep separate per-environment accounts.
wagtailcore.site                  — recreated manually; see docs/promote-staging-to-production.md.
wagtailcore.pagelogentry,
wagtailcore.revision,
wagtailcore.pageviewrestriction   — environment-specific audit/workflow state, not content.
wagtailredirects.*                — redirects are domain-specific.
wagtailsearch.*                   — regenerated via `update_index`.
"""

import json
import os
import sys
from io import StringIO
from pathlib import Path

import dj_database_url
from django.conf import settings
from django.contrib.contenttypes.models import ContentType
from django.core.management import call_command
from django.core.management.base import BaseCommand, CommandError
from django.db import connections
from wagtail.models import Collection, Locale, Page

FULL_MODEL_LABELS = [
    'blog.homepage',
    'blog.projectsindexpage',
    'blog.projectpage',
    'blog.aboutpage',
    'blog.category',
    'pigments',
    'wagtailimages.image',
]

# Fields nulled out after dumping — each points at a deliberately-excluded
# model (see module docstring), all are nullable, and the content itself
# doesn't depend on them.
FIELDS_TO_NULL = {
    'wagtailcore.page': ['owner', 'locked_by', 'live_revision', 'latest_revision'],
    'wagtailimages.image': ['uploaded_by_user'],
}


class Command(BaseCommand):
    help = (
        "One-time sync of staging's content into this run's default database. "
        "See docs/promote-staging-to-production.md for the full procedure."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            '--staging-url',
            default=os.environ.get('STAGING_DATABASE_PUBLIC_URL'),
            help="Staging's public Postgres URL (default: $STAGING_DATABASE_PUBLIC_URL)",
        )
        parser.add_argument(
            '--fixture-path',
            type=Path,
            default=Path(settings.BASE_DIR) / 'staging_sync_fixture.json',
            help='Where to write the combined dump (kept on disk afterward as an audit trail).',
        )
        parser.add_argument(
            '--dry-run',
            action='store_true',
            help='Dump from staging and report counts only — never loads into the target database.',
        )
        parser.add_argument(
            '--noinput',
            action='store_true',
            help='Skip the confirmation prompt before loading (scripted --dry-run use only).',
        )

    def handle(self, *args, **options):
        staging_url = options['staging_url']
        fixture_path = options['fixture_path']
        dry_run = options['dry_run']
        noinput = options['noinput']

        if not staging_url:
            raise CommandError(
                'Missing required configuration:\n'
                '  --staging-url / STAGING_DATABASE_PUBLIC_URL'
            )

        # ConnectionHandler.configure_settings() (which fills in defaults like
        # OPTIONS/CONN_MAX_AGE) insists a 'default' key be present in whatever
        # dict it's given — pass a throwaway copy under that key just to
        # satisfy the check, then discard it.
        raw_config = dj_database_url.parse(staging_url)
        staging_config = connections.configure_settings(
            {'default': dict(raw_config), 'staging': raw_config}
        )['staging']
        settings.DATABASES['staging'] = staging_config
        connections.databases['staging'] = staging_config

        try:
            records = self._dump_from_staging()
            self._remap_shared_references(records)
        except CommandError:
            raise
        except Exception as e:
            self.stderr.write(self.style.ERROR(f'Error dumping from staging: {e}'))
            sys.exit(1)
        finally:
            connections['staging'].close()

        self.stdout.write('')
        for label, count in self._counts_by_model(records).items():
            self.stdout.write(f'  {label}: {count}')
        self.stdout.write(self.style.SUCCESS(f'Dumped {len(records)} records from staging.'))

        fixture_path.write_text(json.dumps(records, indent=2))
        self.stdout.write(f'Wrote fixture to {fixture_path}')

        if dry_run:
            self.stdout.write(self.style.WARNING('[DRY RUN] Not loading into the target database.'))
            return

        if not noinput:
            self.stdout.write(self.style.WARNING(
                "\nThis will load staging content into this run's default database ('default').\n"
                "This assumes 'default' has already been flushed and its Wagtail root page,\n"
                "locale, and root collection restored — see\n"
                "docs/promote-staging-to-production.md. It does not merge page trees, it\n"
                "replaces them.\n"
            ))
            confirm = input("Type 'yes' to continue, or 'no' to cancel: ")
            if confirm != 'yes':
                self.stdout.write('Cancelled.')
                return

        try:
            call_command('loaddata', str(fixture_path))
        except Exception as e:
            self.stderr.write(self.style.ERROR(f'Error loading fixture: {e}'))
            sys.exit(1)

        self.stdout.write(self.style.SUCCESS('Loaded staging content into the default database.'))

    def _dump_from_staging(self):
        records = []

        page_pks = list(
            Page.objects.using('staging').filter(depth__gte=2).values_list('pk', flat=True)
        )
        if page_pks:
            records += self._dumpdata('wagtailcore.page', pks=','.join(map(str, page_pks)))

        for label in FULL_MODEL_LABELS:
            records += self._dumpdata(label)

        for record in records:
            for field_name in FIELDS_TO_NULL.get(record['model'], []):
                record['fields'][field_name] = None

        return records

    def _dumpdata(self, *labels, pks=None):
        buf = StringIO()
        call_command(
            'dumpdata', *labels,
            database='staging',
            pks=pks,
            stdout=buf,
        )
        content = buf.getvalue().strip()
        return json.loads(content) if content else []

    def _remap_shared_references(self, records):
        """
        ContentType, Collection, and Locale rows exist independently on both
        databases (each created its own via migrations) but their pks aren't
        guaranteed to line up — rewrite staging's pk references to the
        target's pk for the same identity before loading. Raises
        CommandError if a referenced row has no counterpart at all on the
        target.
        """
        content_type_ids = self._referenced_ids(records, 'wagtailcore.page', 'content_type')
        locale_ids = self._referenced_ids(records, 'wagtailcore.page', 'locale')
        collection_ids = self._referenced_ids(records, 'wagtailimages.image', 'collection')

        content_type_map = self._build_remap(ContentType, content_type_ids, ('app_label', 'model'), 'content type')
        locale_map = self._build_remap(Locale, locale_ids, ('language_code',), 'locale')
        # Matched by name only — fine while this project has a single "Root"
        # collection; a deeper collection tree would need path-based identity.
        collection_map = self._build_remap(Collection, collection_ids, ('name',), 'collection')

        for record in records:
            if record['model'] == 'wagtailcore.page':
                ct = record['fields'].get('content_type')
                if ct is not None:
                    record['fields']['content_type'] = content_type_map[ct]
                locale = record['fields'].get('locale')
                if locale is not None:
                    record['fields']['locale'] = locale_map[locale]
            elif record['model'] == 'wagtailimages.image':
                coll = record['fields'].get('collection')
                if coll is not None:
                    record['fields']['collection'] = collection_map[coll]

    @staticmethod
    def _referenced_ids(records, model_label, field_name):
        return {
            record['fields'][field_name]
            for record in records
            if record['model'] == model_label and record['fields'].get(field_name) is not None
        }

    @staticmethod
    def _build_remap(model, staging_ids, compare_fields, label):
        if not staging_ids:
            return {}
        staging_rows = {
            row['pk']: tuple(row[f] for f in compare_fields)
            for row in model.objects.using('staging').filter(pk__in=staging_ids).values('pk', *compare_fields)
        }
        # Not .using('staging') — this queries whatever 'default' resolves to
        # for this command invocation, i.e. the target database.
        target_by_identity = {
            tuple(row[f] for f in compare_fields): row['pk']
            for row in model.objects.values('pk', *compare_fields)
        }

        mapping = {}
        missing = []
        for staging_pk, identity in staging_rows.items():
            target_pk = target_by_identity.get(identity)
            if target_pk is None:
                missing.append(f'{label} {identity} (staging pk={staging_pk}): no matching row on target')
            else:
                mapping[staging_pk] = target_pk

        if missing:
            raise CommandError(
                "staging references rows with no counterpart on the target database "
                "(these must already exist there — see docs/promote-staging-to-production.md):\n  "
                + "\n  ".join(missing)
            )
        return mapping

    @staticmethod
    def _counts_by_model(records):
        counts = {}
        for record in records:
            counts[record['model']] = counts.get(record['model'], 0) + 1
        return counts
